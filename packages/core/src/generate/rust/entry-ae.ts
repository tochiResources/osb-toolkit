export function buildRs(): string {
    return `// Generated by osb-toolkit. Compiles the PF_ entry (src/ae_entry.c) and the
// PiPL resource against the After Effects SDK when AE_SDK_DIR is set.
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=src/ae_entry.cpp");
    println!("cargo:rerun-if-env-changed=AE_SDK_DIR");
    let Some(sdk) = std::env::var_os("AE_SDK_DIR").map(PathBuf::from) else {
        return;
    };
    let headers = sdk.join("Headers");
    if !headers.exists() {
        panic!("AE_SDK_DIR does not contain Headers/: {}", sdk.display());
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let includes = [
        headers.clone(),
        headers.join("SP"),
        headers.join("Win"),
        sdk.join("Resources"),
        sdk.join("Util"),
    ];

    // Compile the C entry and the SDK util sources into objects.
    let mut objects: Vec<PathBuf> = Vec::new();
    for source in [
        PathBuf::from("src/ae_entry.cpp"),
        sdk.join("Util/AEGP_SuiteHandler.cpp"),
        sdk.join("Util/MissingSuiteError.cpp"),
    ] {
        let object = out.join(format!(
            "{}.obj",
            source.file_name().unwrap().to_string_lossy()
        ));
        let mut command = Command::new("cl");
        command.args(["/nologo", "/c", "/EHsc", "/MD", "/D", "MSWindows", "/D", "WIN32", "/D", "_WINDOWS"]);
        // Premiere has no SmartFX; the software path is selected via this define.
        if std::env::var_os("CARGO_FEATURE_PREMIERE").is_some() {
            command.arg("/DOSB_PREMIERE");
        }
        for include in &includes {
            command.arg(format!("/I{}", include.display()));
        }
        command.arg(format!("/Fo{}", object.display()));
        command.arg(&source);
        run(&mut command, "cl");
        objects.push(object);
    }

    // PiPL: .r -> .rc (PiPLtool) -> .res (rc) and link the resource.
    let pipl_r = find_pipl();
    let pipl_tool = sdk.join("Resources/PiPLtool.exe");
    let rc_file = out.join("OsbPiPL.rc");
    let res_file = out.join("OsbPiPL.res");
    if pipl_tool.exists() && pipl_r.exists() {
        // cl /EP the .r, then PiPLtool to a .rc, then rc to a .res.
        let rr = out.join("OsbPiPL.rr");
        let mut cl = Command::new("cl");
        cl.args(["/nologo", "/EP"]);
        for include in &includes {
            cl.arg(format!("/I{}", include.display()));
        }
        cl.arg(&pipl_r);
        let expanded = run_capture(&mut cl);
        std::fs::write(&rr, expanded).unwrap();
        let mut pipl = Command::new(&pipl_tool);
        pipl.arg(&rr).arg(&rc_file);
        run(&mut pipl, "PiPLtool");
        let mut rc = Command::new("rc");
        rc.arg(format!("/fo{}", res_file.display())).arg(&rc_file);
        run(&mut rc, "rc");
        println!("cargo:rustc-link-arg={}", res_file.display());
    }

    for object in &objects {
        println!("cargo:rustc-link-arg={}", object.display());
    }
}

fn run(command: &mut Command, what: &str) {
    let status = command.status().unwrap_or_else(|e| panic!("failed to run {what}: {e}"));
    assert!(status.success(), "{what} failed");
}

fn run_capture(command: &mut Command) -> Vec<u8> {
    let output = command.output().expect("failed to run cl /EP");
    output.stdout
}

fn find_pipl() -> PathBuf {
    let dir = PathBuf::from(".");
    if let Ok(entries) = std::fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().map(|e| e == "r").unwrap_or(false) {
                return path;
            }
        }
    }
    PathBuf::from("PiPL.r")
}
`;
}

export function piplR(
    name: string,
    matchName: string,
    category: string,
    config: RustTarget
): string {
    // AE_Effect_Global_OutFlags_2 must match `out_data->out_flags2` from GlobalSetup:
    // AE sets SMART_RENDER (1<<10) | THREADED_RENDERING (1<<27); Premiere has no SmartFX.
    const flags2 = config.target === 'premiere-pro' ? '0x08000000' : '0x08000400';
    return `#include "AEConfig.h"
#include "AE_EffectVers.h"

#ifndef AE_OS_WIN
    #include <AE_General.r>
#endif

resource 'PiPL' (16000) {
    {
        Kind { AEEffect },
        Name { "${name}" },
        Category { "${category}" },
#ifdef AE_OS_WIN
    #if defined(AE_PROC_INTELx64)
        CodeWin64X86 {"EffectMain"},
    #elif defined(AE_PROC_ARM64)
        CodeWinARM64 {"EffectMain"},
    #endif
#elif defined(AE_OS_MAC)
        CodeMacIntel64 {"EffectMain"},
        CodeMacARM64 {"EffectMain"},
#endif
        AE_PiPL_Version { 2, 0 },
        AE_Effect_Spec_Version { PF_PLUG_IN_VERSION, PF_PLUG_IN_SUBVERS },
        AE_Effect_Version { 557057 },
        AE_Effect_Info_Flags { 0 },
        AE_Effect_Global_OutFlags { 0x02000000 },
        AE_Effect_Global_OutFlags_2 { ${flags2} },
        AE_Effect_Match_Name { "${matchName}" },
        AE_Reserved_Info { 0 },
        AE_Effect_Support_URL { "https://osb-toolkit.tochi.moe" }
    }
};
`;
}

export function aeEntryC(name: string, matchName: string, category: string): string {
    return `/* ${name} - PF_ Effect entry generated by osb-toolkit. */
#include "AEConfig.h"

#ifdef AE_OS_WIN
    #include <windows.h>
    #include <commdlg.h>
    #pragma comment(lib, "comdlg32.lib")
#endif

#include "AE_Effect.h"
#include "AE_EffectCB.h"
#include "AE_Macros.h"
#include "AE_EffectCBSuites.h"
#include "Param_Utils.h"
#include "AEGP_SuiteHandler.h"
#include "entry.h"

#include <string.h>

#define OSB_NAME "${name}"
#define OSB_MATCH_NAME "${matchName}"
#define OSB_MAX_PARAMS 512

extern "C" {
void* osb_ae_create(float width, float height);
void osb_ae_destroy(void* handle);
void osb_ae_build(void* handle);
int osb_ae_render(const void* handle, unsigned char* dst, int rowbytes,
                  unsigned int width, unsigned int height, double time, int swap_rb);
unsigned int osb_ae_static_param_count(void);
int osb_ae_static_param_info(unsigned int index, void* out);
int osb_ae_static_param_label(unsigned int index, char* buf, unsigned int len);
int osb_ae_static_param_group(unsigned int index, char* buf, unsigned int len);
void osb_set_param_number(void* handle, unsigned int index, double value);
void osb_set_param_bool(void* handle, unsigned int index, int value);
void osb_set_param_text(void* handle, unsigned int index, const unsigned char* ptr, unsigned int len);
void osb_set_param_color(void* handle, unsigned int index, double r, double g, double b, double a);
}

typedef struct {
    unsigned int kind;
    double min;
    double max;
    double default_number;
    int default_bool;
} OsbParamInfo;

static void* g_instance = NULL;
static int g_params_applied = 0;

/* Descriptor index -> PF param id (topics consume ids) and the reverse map. */
static int g_param_id[OSB_MAX_PARAMS];
static int g_descriptor_for_id[OSB_MAX_PARAMS];

static PF_Err About(PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output)
{
    AEGP_SuiteHandler suites(in_data->pica_basicP);
    suites.ANSICallbacksSuite1()->sprintf(out_data->return_msg, "%s", OSB_NAME);
    return PF_Err_NONE;
}

static PF_Err GlobalSetup(PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output)
{
    out_data->my_version = PF_VERSION(1, 0, 0, PF_Stage_DEVELOP, 1);
    out_data->out_flags = PF_OutFlag_DEEP_COLOR_AWARE;
    /* Threaded rendering also enables Multi-Frame Rendering on AE 2022+. Premiere
       has no SmartFX, so only the software (non-smart) render path is advertised. */
#ifdef OSB_PREMIERE
    out_data->out_flags2 = PF_OutFlag2_SUPPORTS_THREADED_RENDERING;
#else
    out_data->out_flags2 = PF_OutFlag2_SUPPORTS_SMART_RENDER | PF_OutFlag2_SUPPORTS_THREADED_RENDERING;
#endif
    return PF_Err_NONE;
}

static PF_Err ParamsSetup(PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output)
{
    PF_Err err = PF_Err_NONE;
    PF_ParamDef def;
    unsigned int count = osb_ae_static_param_count();
    int id = 1; /* next PF param id; parameter topics consume ids too */
    int in_topic = 0;
    int topic_id = 0;
    char current_group[256];
    current_group[0] = 0;
    for (unsigned int i = 0; i < OSB_MAX_PARAMS; ++i) g_descriptor_for_id[i] = -1;

    for (unsigned int i = 0; i < count; ++i)
    {
        OsbParamInfo info;
        char label[256];
        char group[256];
        if (!osb_ae_static_param_info(i, &info)) continue;
        label[0] = 0;
        osb_ae_static_param_label(i, label, sizeof(label));
        group[0] = 0;
        osb_ae_static_param_group(i, group, sizeof(group));

        /* Open/close parameter topics as the group changes, so a bundle's
           parameters are grouped per source effect. */
        if (strcmp(group, current_group) != 0)
        {
            if (in_topic) { PF_END_TOPIC(topic_id); id += 1; in_topic = 0; }
            if (group[0]) { PF_ADD_TOPIC(group, id); topic_id = id; id += 1; in_topic = 1; }
            strcpy(current_group, group);
        }

        AEFX_CLR_STRUCT(def);
        switch (info.kind)
        {
        case 1: /* checkbox */
            PF_ADD_CHECKBOX(label, "", info.default_bool ? 1 : 0, 0, id);
            break;
        case 2: /* color */
            PF_ADD_COLOR(label, PF_MAX_CHAN8, PF_MAX_CHAN8, PF_MAX_CHAN8, id);
            break;
        case 7: /* picker -> a button that opens a host file picker */
            PF_ADD_BUTTON(label, "", NULL, PF_ParamFlag_NONE, id);
            break;
        default: /* slider / angle */
            PF_ADD_FLOAT_SLIDERX(label, (PF_FpLong)info.min, (PF_FpLong)info.max,
                                 (PF_FpLong)info.min, (PF_FpLong)info.max,
                                 (PF_FpLong)info.default_number, PF_Precision_HUNDREDTHS, 0, 0, id);
            break;
        }
        g_param_id[i] = id;
        if (id < OSB_MAX_PARAMS) g_descriptor_for_id[id] = (int)i;
        id += 1;
    }
    if (in_topic) { PF_END_TOPIC(topic_id); id += 1; }
    out_data->num_params = id - 1;
    return err;
}

static PF_Err SequenceSetup(PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output)
{
    g_instance = osb_ae_create((float)out_data->width, (float)out_data->height);
    g_params_applied = 0;
    return PF_Err_NONE;
}

static PF_Err SequenceResetup(PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output)
{
    if (g_instance) { osb_ae_destroy(g_instance); g_instance = NULL; }
    return SequenceSetup(in_data, out_data, params, output);
}

/* Applies the current host parameter values to the effect, then builds once. */
static void ApplyParamsAndBuild(PF_InData* in_data, PF_ParamDef* params[])
{
    if (!g_instance || g_params_applied) return;
    unsigned int count = osb_ae_static_param_count();
    for (unsigned int i = 0; i < count; ++i)
    {
        OsbParamInfo info;
        if (!osb_ae_static_param_info(i, &info)) continue;
        int id = g_param_id[i];
        if (id <= 0 || id >= OSB_MAX_PARAMS) continue;
        PF_ParamDef* def = params[id];
        switch (info.kind)
        {
        case 1: /* checkbox */
            osb_set_param_bool(g_instance, i, def->u.bd.value);
            break;
        case 0: /* slider */
        case 3: /* angle */
            osb_set_param_number(g_instance, i, (double)def->u.fs_d.value);
            break;
        case 2: /* color */
            osb_set_param_color(g_instance, i,
                def->u.cd.value.red / 255.0, def->u.cd.value.green / 255.0,
                def->u.cd.value.blue / 255.0, 1.0);
            break;
        default:
            break;
        }
    }
    osb_ae_build(g_instance);
    g_params_applied = 1;
}

static PF_Err UserChangedParam(PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output, void* extra)
{
    /* A picker button was pressed: open a file picker and store the path. */
    PF_UserChangedParamExtra* changed = (PF_UserChangedParamExtra*)extra;
    unsigned int pf_id = changed ? (unsigned int)changed->param_index : 0;
    if (pf_id == 0 || pf_id >= OSB_MAX_PARAMS || !g_instance) return PF_Err_NONE;
    int descriptor = g_descriptor_for_id[pf_id];
    if (descriptor < 0) return PF_Err_NONE;
    OsbParamInfo info;
    if (!osb_ae_static_param_info((unsigned int)descriptor, &info) || info.kind != 7) return PF_Err_NONE;
#ifdef AE_OS_WIN
    char path[MAX_PATH] = {0};
    OPENFILENAMEA ofn;
    ZeroMemory(&ofn, sizeof(ofn));
    ofn.lStructSize = sizeof(ofn);
    ofn.hwndOwner = NULL;
    ofn.lpstrFile = path;
    ofn.nMaxFile = MAX_PATH;
    ofn.lpstrFilter = "Media (images, audio, fonts)\\0*.png;*.jpg;*.jpeg;*.wav;*.mp3;*.ogg;*.ttf;*.otf\\0All files\\0*.*\\0";
    ofn.Flags = OFN_FILEMUSTEXIST | OFN_PATHMUSTEXIST | OFN_NOCHANGEDIR;
    if (GetOpenFileNameA(&ofn))
    {
        osb_set_param_text(g_instance, (unsigned int)descriptor, (const unsigned char*)path, (unsigned int)strlen(path));
        g_params_applied = 0;
    }
#endif
    return PF_Err_NONE;
}

static PF_Err Render(PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output)
{
    ApplyParamsAndBuild(in_data, params);
    if (g_instance)
    {
        double time_ms = (double)in_data->current_time / (double)in_data->time_scale * 1000.0;
#ifdef OSB_PREMIERE
        int swap_rb = 1; /* Premiere prefers BGRA */
#else
        int swap_rb = 0;
#endif
        osb_ae_render(g_instance, (unsigned char*)output->data, output->rowbytes,
                      (unsigned int)output->width, (unsigned int)output->height, time_ms, swap_rb);
    }
    return PF_Err_NONE;
}

extern "C" DllExport PF_Err EffectMain(
    PF_Cmd cmd, PF_InData* in_data, PF_OutData* out_data, PF_ParamDef* params[], PF_LayerDef* output, void* extra)
{
    PF_Err err = PF_Err_NONE;
    try
    {
        switch (cmd)
        {
        case PF_Cmd_ABOUT: err = About(in_data, out_data, params, output); break;
        case PF_Cmd_GLOBAL_SETUP: err = GlobalSetup(in_data, out_data, params, output); break;
        case PF_Cmd_PARAMS_SETUP: err = ParamsSetup(in_data, out_data, params, output); break;
        case PF_Cmd_SEQUENCE_SETUP: err = SequenceSetup(in_data, out_data, params, output); break;
        case PF_Cmd_SEQUENCE_RESETUP: err = SequenceResetup(in_data, out_data, params, output); break;
        case PF_Cmd_USER_CHANGED_PARAM: err = UserChangedParam(in_data, out_data, params, output, extra); break;
        case PF_Cmd_RENDER: err = Render(in_data, out_data, params, output); break;
        default: break;
        }
    }
    catch (PF_Err& thrown) { err = thrown; }
    return err;
}

extern "C" DllExport PF_Err PluginDataEntryFunction2(
    PF_PluginDataPtr inPtr, PF_PluginDataCB2 inPluginDataCallBackPtr,
    SPBasicSuite* inSPBasicSuitePtr, const char* inHostName, const char* inHostVersion)
{
    PF_Err result = PF_Err_INVALID_CALLBACK;
    result = PF_REGISTER_EFFECT_EXT2(
        inPtr, inPluginDataCallBackPtr, OSB_NAME, OSB_MATCH_NAME, "${category}",
        AE_RESERVED_INFO, "EffectMain", "https://osb-toolkit.tochi.moe");
    return result;
}
`;
}

/**
 * Build script for Resolve/OFX crates. No-ops unless the OFX SDK is present
 * (OFX_SDK_DIR env or the vendored `../../vendor/openfx`); then it compiles the
 * OFX entry against the headers and links it into the `.ofx` binary.
 */
