import type {
    EffectParameter,
    EffectScript,
    PluginParameter,
    PluginSpec,
} from '@tochii/osb-toolkit-shared';

import { rustSnakeCase, transpileCSharpToRust } from '../../csharp/rust/index.js';
import type { RustTarget } from './targets.js';

export function buildLibRs(input: {
    script: EffectScript;
    spec: PluginSpec;
    config: RustTarget;
    body: string;
    libraries?: EffectScript[];
    libraryMethods?: Record<string, string>;
}): string {
    const { script, spec, config, body, libraries, libraryMethods } = input;
    const structName = rustStructName(spec.name);
    const rtLibraryMethods = buildRtLibraryMethods(libraries ?? []);
    return buildEffectLibRs({
        spec,
        config,
        structName,
        fields: script.parameters
            .map(
                parameter =>
                    `    pub ${rustSnakeCase(parameter.name)}: ${rustFieldType(parameter)},`
            )
            .join('\n'),
        parameterLines: spec.parameters
            .map(parameter => `            ${rustParameterDescriptor(parameter)},`)
            .join('\n'),
        setArms: script.parameters
            .map(parameter => `            "${parameter.name}" => { ${rustSetArm(parameter)} }`)
            .join('\n'),
        generateBody: body,
        helpers:
            buildHelperMethods(script, {
                structName,
                libraryMethods,
                rtHelpers: computeRtHelpers(script),
                rtLibraryMethods,
            }) +
            (libraries ?? [])
                .map(library =>
                    buildHelperMethods(library, {
                        structName,
                        prefix: rustSnakeCase(library.className),
                        libraryMethods,
                        rtHelpers: computeRtHelpers(library),
                        rtLibraryMethods,
                    })
                )
                .join(''),
        header: `${spec.name} - generated by osb-toolkit from an effect script.`,
    });
}

/** Maps external library static methods (`Class.Method`) to their Rust method names. */
export function buildLibraryMethods(libraries: EffectScript[]): Record<string, string> {
    const methods: Record<string, string> = {};
    for (const library of libraries) {
        const prefix = rustSnakeCase(library.className);
        for (const method of library.methods) {
            methods[`${library.className}.${method.name}`] =
                `${prefix}_${rustSnakeCase(method.name)}`;
        }
    }
    return methods;
}

/** C# identifiers meaning a helper body needs `rt` (generator/context APIs). */
const RT_REFERENCE_TOKENS = [
    'GetLayer',
    'GetBeatmap',
    'Random',
    'GetFft',
    'GetMapsetBitmap',
    'AudioDuration',
    'Beatmap',
];

/**
 * The C# helper methods of `script` whose emitted Rust method takes `rt`,
 * directly (the body uses a generator/context API) or transitively (it calls
 * such a helper). Helpers that do not need `rt` are emitted without it, so
 * passing `rt` never conflicts with a sprite command's receiver borrow.
 */
export function computeRtHelpers(script: EffectScript): Set<string> {
    const methods = script.methods.filter(method => method.name !== 'Generate');
    const needs = new Set<string>();
    let changed = true;
    while (changed) {
        changed = false;
        for (const method of methods) {
            if (needs.has(method.name)) continue;
            const body = method.body ?? '';
            const direct = RT_REFERENCE_TOKENS.some(token =>
                new RegExp(`\\b${token}\\b`).test(body)
            );
            const transitive = [...needs].some(helper =>
                new RegExp(`\\b${helper}\\s*\\(`).test(body)
            );
            if (direct || transitive) {
                needs.add(method.name);
                changed = true;
            }
        }
    }
    return needs;
}

/** The `Class.Method` keys of helpers that need `rt`, for all libraries. */
export function buildRtLibraryMethods(libraries: EffectScript[]): string[] {
    const keys: string[] = [];
    for (const library of libraries) {
        for (const method of computeRtHelpers(library)) {
            keys.push(`${library.className}.${method}`);
        }
    }
    return keys;
}

/** The precomputed pieces of a generated `lib.rs`; shared by single and bundle emitters. */
export interface EffectLibInput {
    spec: PluginSpec;
    config: RustTarget;
    structName: string;
    /** Struct field lines (one `pub name: Type,` per line). */
    fields: string;
    /** `ParameterDescriptor::new(..)` lines. */
    parameterLines: string;
    /** `set_parameter` match arms. */
    setArms: string;
    /** The `generate()` body (already transpiled and merged). */
    generateBody: string;
    /** Inherent helper methods (`\n\nimpl .. { .. }` or empty). */
    helpers: string;
    /** `//!` module doc line. */
    header: string;
}

export function buildEffectLibRs(input: EffectLibInput): string {
    const {
        spec,
        config,
        structName,
        fields,
        parameterLines,
        setArms,
        generateBody,
        helpers,
        header,
    } = input;
    const extraUse = config.extraUse.length > 0 ? `\n${config.extraUse.join('\n')}` : '';
    const hostGlue = config.hostGlue
        ? `\n// Emits the host C ABI (osb_*) the entry shim in src/*_entry.cpp calls.\n#[cfg(feature = "host")]\n${config.hostGlue}!(${structName});\n`
        : '';
    const hostGlueOfx =
        config.hostEntry === 'ofx'
            ? `\n// Emits the host C ABI (osb_ofx_*) the OFX entry shim calls.\n#[cfg(feature = "host")]\n${config.hostGlue}!(${structName});\n`
            : '';
    const glue = config.hostEntry === 'ofx' ? hostGlueOfx : hostGlue;

    return `//! ${header}
#![allow(unused_variables, unused_mut, non_snake_case)]

use osb_runtime::prelude::*;${extraUse}

/// The converted \`${spec.name}\` effect.
#[derive(Default)]
pub struct ${structName} {
${fields || '    // no configurables'}
}

impl Effect for ${structName} {
    fn generate(&mut self, ctx: &mut Context) -> Storyboard {
        let mut storyboard = Storyboard::new();
        self.generate_into(&mut storyboard, ctx);
        storyboard
    }

    fn parameters(&self) -> Vec<ParameterDescriptor> {
        vec![
${parameterLines || '            // no configurables'}
        ]
    }

    fn set_parameter(&mut self, name: &str, value: &ParameterValue) {
        match name {
${setArms || '            _ => {}'}
            _ => {}
        }
    }
}

impl ${structName} {
    /// The transpiled \`Generate()\` body, building into \`storyboard\`.
    fn generate_into(&mut self, storyboard: &mut Storyboard, ctx: &mut Context) {
        let mut rt = Runtime { storyboard, context: ctx };
${indent(generateBody, '        ')}
    }
}${helpers}
${glue}`;
}

/**
 * Emits the effect's non-`Generate` methods as inherent methods on the struct.
 * Their bodies are transpiled with the same configurable/helper mappings, so a
 * helper can read configurables and call other helpers. `prefix` namespaces the
 * methods (and their call sites via `names`) when bundling.
 */
export function buildHelperMethods(
    script: EffectScript,
    options: {
        structName: string;
        names?: Record<string, string>;
        prefix?: string;
        libraryMethods?: Record<string, string>;
        rtHelpers?: Set<string>;
        rtLibraryMethods?: string[];
    }
): string {
    // The `.osb` importer's helpers implement its hand-written parser, which the
    // runtime replaces (`Runtime::import_osb`), so they are not emitted.
    if (script.importOsb) return '';
    const helperNames = script.methods
        .filter(method => method.name !== 'Generate')
        .map(m => m.name);
    const methods = script.methods
        .filter(method => method.name !== 'Generate' && method.body)
        .map(method => {
            const signature = method.signature;
            const parenIndex = signature.indexOf('(');
            const head = signature.slice(0, parenIndex).trim().split(/\s+/);
            const name = head.pop() ?? method.name;
            const returnType = rustTypeName(head.join(' '));
            const paramsText = signature.slice(parenIndex + 1, signature.lastIndexOf(')')).trim();
            const spriteNames: string[] = [];
            const layerNames: string[] = [];
            const params = paramsText
                ? paramsText
                      .split(',')
                      .map(param => {
                          const trimmed = param.trim();
                          const lastSpace = trimmed.lastIndexOf(' ');
                          let type = trimmed.slice(0, lastSpace).trim();
                          const paramName = trimmed.slice(lastSpace + 1);
                          const isRef = /^(ref|out|in)\s+/.test(type);
                          type = type.replace(/^(ref|out|in)\s+/, '');
                          const rustType = rustTypeName(type);
                          // Sprite/layer handles are `Copy` and pass by value, so a
                          // helper can hold one while it also uses `rt`.
                          if (rustType === 'SpriteHandle') {
                              spriteNames.push(paramName);
                              return `${paramName}: SpriteHandle`;
                          }
                          if (rustType === 'LayerHandle') {
                              layerNames.push(paramName);
                              return `${paramName}: LayerHandle`;
                          }
                          // Other C# reference types pass as a shared reference.
                          const prefix = isRef || REFERENCE_TYPES.has(rustType) ? '&' : '';
                          return `${paramName}: ${prefix}${rustType}`;
                      })
                      .join(', ')
                : '';
            const body = transpileCSharpToRust(method.body, {
                configurableNames: script.parameters.map(parameter => parameter.name),
                helperNames,
                names: options.names,
                libraryMethods: options.libraryMethods,
                spriteNames,
                layerNames,
                rtHelpers: [...(options.rtHelpers ?? [])],
                rtLibraryMethods: options.rtLibraryMethods,
            }).code;
            const rustName = options.prefix
                ? `${options.prefix}_${rustSnakeCase(name)}`
                : rustSnakeCase(name);
            // Helpers that use generator APIs receive `rt`; all helpers take
            // `&mut self` so they can read/write configurables.
            const rtParam = options.rtHelpers?.has(method.name) ? 'rt: &mut Runtime, ' : '';
            return `\n    fn ${rustName}(&mut self, ${rtParam}${params}) -> ${returnType} {\n${indent(body, '        ')}\n    }`;
        })
        .join('\n');

    return methods ? `\n\nimpl ${options.structName} {${methods}\n}` : '';
}

/** C# types that are reference types (passed as a handle), mapped to `&T`. */
const REFERENCE_TYPES = new Set([
    'OsbSprite',
    'OsbAnimation',
    'Camera',
    'Scene3d',
    'Sprite3d',
    'Node3d',
    'Object3d',
    'StoryboardSegment',
    'Layer',
]);

/** Maps a C# method parameter/return type to the generated Rust type. */
function rustTypeName(csType: string): string {
    switch (csType.replace(/\s+/g, '')) {
        case 'void':
            return '()';
        case 'bool':
            return 'bool';
        case 'string':
            return 'String';
        case 'Vector2':
        case 'OpenTK.Vector2':
        case 'osuTK.Vector2':
            return 'Vec2';
        case 'Vector3':
        case 'OpenTK.Vector3':
        case 'osuTK.Vector3':
            return 'Vec3';
        case 'Vector4':
        case 'OpenTK.Vector4':
        case 'osuTK.Vector4':
            return 'Vec4';
        case 'Matrix4':
        case 'OpenTK.Matrix4':
        case 'osuTK.Matrix4':
            return 'Matrix4';
        case 'Quaternion':
        case 'OpenTK.Quaternion':
        case 'osuTK.Quaternion':
            return 'Quaternion';
        case 'Color4':
        case 'CommandColor':
        case 'OpenTK.Graphics.Color4':
        case 'osuTK.Graphics.Color4':
            return 'Color4';
        case 'OsbOrigin':
            return 'OsbOrigin';
        case 'OsbEasing':
            return 'Easing';
        case 'Bitmap':
            return 'Bitmap';
        case 'OsbSprite':
        case 'OsbAnimation':
            return 'SpriteHandle';
        case 'Layer':
        case 'StoryboardSegment':
            return 'LayerHandle';
        default:
            return 'f64';
    }
}

/** Maps a configurable's type to the Rust struct field type. */
export function rustFieldType(parameter: EffectParameter): string {
    switch (parameter.type) {
        // C# numeric configurables are stored as f64 so they mix freely with the
        // f64 times/values the runtime uses; integer-only uses are cast at the
        // point of use by the transpiler.
        case 'int':
        case 'long':
        case 'double':
        case 'float':
            return 'f64';
        case 'bool':
            return 'bool';
        case 'string':
            return 'String';
        case 'vec2':
            return 'Vec2';
        case 'vec3':
            return 'Vec3';
        case 'color':
            return 'Color4';
        case 'origin':
            return 'OsbOrigin';
        case 'easing':
            return 'Easing';
        case 'enum':
            return 'i32';
        default:
            return 'f64';
    }
}

/** Emits the `set_parameter` arm body that assigns a configurable field. */
export function rustSetArm(parameter: EffectParameter): string {
    const field = `self.${rustSnakeCase(parameter.name)}`;
    switch (parameter.type) {
        case 'int':
        case 'long':
        case 'double':
        case 'float':
            return `if let ParameterValue::Number(v) = value { ${field} = *v; }`;
        case 'bool':
            return `if let ParameterValue::Bool(v) = value { ${field} = *v; }`;
        case 'string':
            return `if let ParameterValue::Text(v) = value { ${field} = v.clone(); }`;
        case 'vec2':
        case 'vec3':
            return `if let ParameterValue::Point(v) = value { ${field} = *v; }`;
        case 'color':
            return `if let ParameterValue::Color(v) = value { ${field} = *v; }`;
        case 'origin':
            return `if let ParameterValue::Choice(i) = value { ${field} = OsbOrigin::from_index(*i as usize); }`;
        case 'easing':
            return `if let ParameterValue::Choice(i) = value { ${field} = Easing::from_id(*i as u8).unwrap_or(Easing::None); }`;
        case 'enum':
            return `if let ParameterValue::Choice(i) = value { ${field} = *i; }`;
        default:
            return `let _ = value;`;
    }
}

export function rustParameterDescriptor(parameter: PluginParameter): string {
    const descriptor = `ParameterDescriptor::new("${parameter.name}", ${rustControl(parameter)}, ${rustDefault(parameter)})`;
    if (!parameter.group) return descriptor;
    return `${descriptor}.with_group("${parameter.group.replace(/"/g, '\\"')}")`;
}

function rustControl(parameter: PluginParameter): string {
    switch (parameter.control) {
        case 'checkbox':
            return 'Control::Checkbox';
        case 'color':
            return 'Control::Color';
        case 'angle':
            return 'Control::Angle';
        case 'point':
            return 'Control::Point';
        case 'text':
            return 'Control::Text';
        case 'picker':
            return `Control::Picker { asset_kind: "${parameter.assetKind ?? 'file'}".into() }`;
        case 'popup': {
            const choices = (parameter.enumValues ?? [])
                .map(choice => `"${choice.name}".into()`)
                .join(', ');
            return `Control::Popup { choices: vec![${choices}] }`;
        }
        default:
            return `Control::Slider { min: ${rustFloat(parameter.min ?? 0)}, max: ${rustFloat(parameter.max ?? 1000)} }`;
    }
}

function rustDefault(parameter: PluginParameter): string {
    const value = parameter.defaultValue;
    switch (parameter.control) {
        case 'checkbox':
            return `ParameterValue::Bool(${value === true ? 'true' : 'false'})`;
        case 'color':
            return 'ParameterValue::Color(Color4::WHITE)';
        case 'point':
            return 'ParameterValue::Point(Vec2::ZERO)';
        case 'popup':
        case 'picker': {
            const index =
                parameter.control === 'popup'
                    ? Math.max(
                          0,
                          (parameter.enumValues ?? []).findIndex(choice => choice.name === value)
                      )
                    : 0;
            return `ParameterValue::Choice(${index})`;
        }
        case 'text':
            return `ParameterValue::Text("${String(value ?? '').replace(/"/g, '\\"')}".into())`;
        default:
            return `ParameterValue::Number(${rustFloat(typeof value === 'number' ? value : 0)})`;
    }
}

/** Emits a Rust float literal (integer literals do not coerce to f64). */
function rustFloat(value: number): string {
    return Number.isInteger(value) ? `${value}.0` : String(value);
}

export function rustCrateName(name: string): string {
    const snake = name
        .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '');
    return /^[0-9]/.test(snake) ? `osb_${snake}` : snake || 'osb_effect';
}

export function rustStructName(name: string): string {
    const cleaned = name.replace(/[^A-Za-z0-9_]/g, '_');
    return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned || 'Effect';
}

export function indent(text: string, prefix: string): string {
    return text
        .split('\n')
        .map(line => (line.trim() ? `${prefix}${line}` : line))
        .join('\n');
}

/** Prepends the built-in concurrency configurables to an effect's parameters. */
export function withConcurrencyParameters(spec: PluginSpec): PluginSpec {
    const builtins: PluginParameter[] = [
        {
            name: 'Multithreading',
            label: 'Multi-threading',
            scriptName: 'multithreading',
            csType: 'bool',
            type: 'bool',
            control: 'checkbox',
            defaultValue: true,
            description:
                'Render concurrently. On After Effects this sets the threaded-rendering flag, which also enables Multi-Frame Rendering (AE 2022+); on OFX/Resolve it declares full render thread-safety. On by default where the host supports it, hidden on unsupported host versions.',
            order: -2,
        },
        {
            name: 'ThreadCount',
            label: 'Thread count (0 = auto)',
            scriptName: 'threadCount',
            csType: 'int',
            type: 'int',
            control: 'slider',
            defaultValue: 0,
            min: 0,
            max: 64,
            description: 'Worker threads for rendering; 0 uses the host/available parallelism.',
            order: -1,
        },
    ];
    return { ...spec, parameters: [...builtins, ...spec.parameters] };
}
