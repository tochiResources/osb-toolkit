import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { root } from '../shared';

const template = join(dirname(fileURLToPath(import.meta.url)), 'osbtk_clean.hpp');
const output = join(root, 'bindings', 'cpp', 'osbtk_clean.hpp');

/**
 * Writes the clean C++ header from its maintained template. The C++ SDK has no
 * OpenAPI generator stage, so the template is the source of truth for the
 * header and `yarn openapi` owns the checked-in copy.
 */
export function generateCpp(): void {
    const body = readFileSync(template, 'utf8').replace(/^#pragma once\n/, '');
    const header = [
        '// <auto-generated/>',
        '// Generated from scripts/generate-openapi/cpp/osbtk_clean.hpp; do not edit.',
        '#pragma once',
        '',
        body,
    ].join('\n');
    writeFileSync(output, header, 'utf8');
    console.log(`openapi: generated C++ clean clients into ${output}`);
}
