import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { autoGeneratedHeader, runGenerator, targets, walk } from '../shared';
import { emitCSharpClient, extendCSharpErrors, protectCSharpTransport } from './post-process';

/** Generates the C# SDK (models + one API class per tag + the client). */
export function generateCSharp(): void {
    const out = mkdtempSync(join(tmpdir(), 'osbtk-ogen-'));
    try {
        runGenerator({
            out,
            generator: 'csharp',
            globalProperty: 'models,apis,supportingFiles',
            additionalProperties:
                'packageName=tochiRes.osbTK,library=httpclient,targetFramework=net10.0,netCoreProjectFile=true,nullableReferenceTypes=true,generateSyncMethods=true,apiNameSuffix=API,removeOperationIdPrefix=true,removeOperationIdPrefixDelimiter=.',
        });

        const source = join(out, 'src', 'tochiRes.osbTK');
        rmSync(targets.csharp, { recursive: true, force: true });
        mkdirSync(targets.csharp, { recursive: true });
        for (const part of ['Model', 'Api', 'Client']) {
            cpSync(join(source, part), join(targets.csharp, part), { recursive: true });
        }

        for (const file of walk(targets.csharp)) {
            if (!file.endsWith('.cs')) {
                continue;
            }
            const text = readFileSync(file, 'utf8');
            if (!text.startsWith('// <auto-generated/>')) {
                writeFileSync(file, autoGeneratedHeader + text, 'utf8');
            }
        }
        protectCSharpTransport(join(targets.csharp, 'Api'));
        extendCSharpErrors(join(targets.csharp, 'Client'));
        emitCSharpClient();
        console.log(`openapi: generated C# SDK into ${targets.csharp}`);
    } finally {
        rmSync(out, { recursive: true, force: true });
    }
}
