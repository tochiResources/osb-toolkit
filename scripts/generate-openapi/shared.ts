import { execSync } from 'node:child_process';
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Regenerates the OpenAPI contract from the Rust source of truth
// (`crates/osb-api`) and the per-language SDK models/clients from it. Rust is
// authoritative: never edit `bindings/openapi/osbtk.openapi.json` or the
// generated SDK files by hand.

/** The repository root (this file lives at `scripts/generate-openapi/`). */
export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The checked-in OpenAPI contract. */
export const specPath = join(root, 'bindings', 'openapi', 'osbtk.openapi.json');

/** Every generated SDK target. */
export const targets = {
    csharp: join(root, 'bindings', 'csharp', 'tochiRes.osbTK', 'src', 'generated'),
    typescript: join(root, 'packages', 'sdk', 'src', 'lib'),
    python: join(root, 'bindings', 'python', 'osbtk'),
    go: join(root, 'bindings', 'go', 'osbtk'),
    java: join(root, 'bindings', 'java', 'src', 'main', 'java'),
    rust: join(root, 'crates', 'osb-sdk', 'src', 'models'),
};

/** The header every generated C# file carries. */
export const autoGeneratedHeader = '// <auto-generated/>\n#nullable disable\n';

/** Regenerates the contract from `crates/osb-api` and writes it to disk. */
export function writeSpec(): void {
    const spec = execSync('tsx scripts/cargo.ts run -q -p osb-api --bin osbtk-openapi', {
        cwd: root,
        encoding: 'utf8',
        shell: true,
    });
    mkdirSync(dirname(specPath), { recursive: true });
    writeFileSync(specPath, spec.endsWith('\n') ? spec : `${spec}\n`, 'utf8');
    console.log(`openapi: wrote ${specPath}`);
}

/** Every file under `directory`, recursively. */
export function walk(directory: string): string[] {
    return readdirSync(directory).flatMap(entry => {
        const path = join(directory, entry);
        return statSync(path).isDirectory() ? walk(path) : [path];
    });
}

/** Runs `openapi-generator-cli generate` with the shared contract input. */
export function runGenerator(options: {
    out: string;
    generator: string;
    globalProperty: string;
    additionalProperties: string;
}): void {
    execSync(
        [
            'yarn openapi-generator-cli generate',
            `-i "${specPath}"`,
            `-g ${options.generator}`,
            `-o "${options.out}"`,
            `--global-property=${options.globalProperty}`,
            `--additional-properties=${options.additionalProperties}`,
        ].join(' '),
        { cwd: root, stdio: 'inherit', shell: true }
    );
}
